"""Behavioral Verilog model emitter, on the pin contract.

Same names, same widths, same bit order as the LEF (Library Exchange
Format) abstract: docs/pin_interface.md (section 5) makes the three
views interchangeable, and sramforge/pins.py is the one place all of
them take their pin list from.  The behaviour mirrors the asap7_sram_0p0
reference model (srambank_64x4x64_6t122.v): synchronous single
read/write port, output latched and updated on a read only.

What the model adds beyond the reference: the sparse-bits address space.
Below the decode frame's full width the layout simply has no cells and
no wordline driver for column codes >= bits (generator.py), so a write
to such an address is dropped and a read returns x, which is what an
equalized bitline pair through the sense amplifier really yields.
"""
from .generator import BankSpec
from . import pins as contract


def emit_verilog(spec: BankSpec) -> str:
    from . import sense
    st = sense.sdel_code(spec, "TT")
    # the measured code (sdel<4> first in Verilog bus order); "xxxxx"
    # when no code of the placed control reaches this bank's far row
    sdel = st["code"][::-1] if st["code"] else "xxxxx"
    a = contract.address_width(spec)
    w = contract.data_width(spec)
    words = contract.word_count(spec)
    mux = contract.mux_bits(spec)
    col = contract.column_bits(spec)
    bits = spec.bits_per_group
    ra, rw = f"[{a - 1}:0]".ljust(9), f"[{w - 1}:0]".ljust(9)
    return f"""// Behavioral model generated by sramforge.
// Single-port (one read/write port) SRAM (Static Random-Access Memory):
// {words} words x {w} bits, {a} address bits.
// Port names and widths follow docs/pin_interface.md, the same contract
// the LEF (Library Exchange Format) abstract of this bank is written from.
// Measured address map: ADDRESS[{mux - 1}:0] = column-mux select,
// ADDRESS[{mux + col - 1}:{mux}] = wordline column, ADDRESS[{a - 1}] = half select.
// Column codes >= {bits} have no cells in the layout (sparse-bits scheme):
// a write there is dropped and a read returns x.
module {spec.name} (
      input                  clk
    , input      {ra} ADDRESS
    , input      {rw} wd            // write data
    , input                  banksel       // access enable (active high); nothing happens when low
    , input                  read          // read enable
    , input                  byte_wrenab   // write enable
    , input      [4:0]       sdel          // sense-timing delay-line code: accepted, functionally ignored (tie to 5'b{sdel})
    , output reg {rw} dataout       // read data, latched; holds between reads
);

  reg [{w - 1}:0] mem [0:{(1 << a) - 1}];   // {1 << a} address codes, {words} implemented

  wire [{col - 1}:0] column = ADDRESS[{mux + col - 1}:{mux}];
  wire live = (column < {bits});         // the column exists in the layout

  always @(posedge clk) begin
    if (banksel & byte_wrenab & live)
      mem[ADDRESS] <= wd;
    if (banksel & read)
      dataout <= live ? mem[ADDRESS] : {{{w}{{1'bx}}}};   // held until the next read
  end

endmodule // {spec.name}
"""
