#!/usr/bin/env python3
"""Write the structural consumer netlist that static timing analysis
links against the generated macro.

Deliberately not synthesized: the design is nothing but registers around
the macro, so a mapper has no logic to optimize and only introduces tool
friction (ASAP7 ships inverting-output flip-flops, which a synthesizer
leaves as behavioural inversions that a timer will not parse).  Writing
the flip-flop and inverter instances directly keeps the netlist exactly
as intended and keeps the test about the macro's library.
"""
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from sramforge import BankSpec, pins as contract               # noqa: E402

DFF = "DFFHQNx1_ASAP7_75t_R"        # ASAP7 has inverting-output flops only
INV = "INVx1_ASAP7_75t_R"


def reg(name, d, q):
    """A register whose true output is q: flop with inverted output plus
    an inverter."""
    return [f"  {DFF} ff_{name} (.D({d}), .CLK(clk), .QN(n_{name}));",
            f"  {INV} iv_{name} (.A(n_{name}), .Y({q}));",
            f"  wire n_{name};"]


def main() -> int:
    spec = BankSpec()
    a = contract.address_width(spec)
    w = contract.data_width(spec)
    body, ports = [], []
    for i in range(a):
        body += reg(f"addr{i}", f"addr_i[{i}]", f"addr_q[{i}]")
    for s in ("banksel", "read", "wren"):
        body += reg(s, f"{s}_i", f"{s}_q")
    for i in range(w):
        body += reg(f"wd{i}", f"wd_i[{i}]", f"wd_q[{i}]")
        body += reg(f"do{i}", f"dout[{i}]", f"dout_o[{i}]")
    v = [f"// generated by sta/make_wrapper.py for {spec.name}",
         "module sram_wrapper (clk, addr_i, banksel_i, read_i, wren_i,",
         "                     wd_i, dout_o);",
         "  input clk, banksel_i, read_i, wren_i;",
         f"  input [{a - 1}:0] addr_i;",
         f"  input [{w - 1}:0] wd_i;",
         f"  output [{w - 1}:0] dout_o;",
         f"  wire [{a - 1}:0] addr_q;",
         f"  wire [{w - 1}:0] wd_q, dout;",
         f"  wire [{w - 1}:0] dout_o;",
         "  wire banksel_q, read_q, wren_q;"]
    # the delay-line code this configuration needs, as a constant: the
    # timer treats it as a tied net, which is what a real integration
    # does with a compile-time strap
    from sramforge import sense
    code = sense.sdel_code(spec, "TT")["code"] or "11111"
    v += body
    v += [f"  {spec.name} u_sram (.clk(clk), .ADDRESS(addr_q), "
          ".banksel(banksel_q), .read(read_q), .byte_wrenab(wren_q),",
          f"      .sdel(5'b{code[::-1]}), .wd(wd_q), .dataout(dout));",
          "endmodule"]
    out = REPO / "sta" / "synth_wrapper.v"
    out.write_text("\n".join(v) + "\n")
    print(f"wrote {out}: {a} address, {w} data bits, sdel tied to {code}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
